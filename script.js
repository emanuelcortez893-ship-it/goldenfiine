let cart = JSON.parse(localStorage.getItem("gf_cart") || "[]");
let category = "Todos";
let current = null;


// =========================
// FUNCIONES GENERALES
// =========================

function money(value) {
  return new Intl.NumberFormat("es-AR", {
    style: "currency",
    currency: "ARS",
    maximumFractionDigits: 0
  }).format(value);
}

function save() {
  localStorage.setItem("gf_cart", JSON.stringify(cart));
}


// =========================
// CATEGORÍAS
// =========================

function setCategory(cat) {
  category = cat;

  document.querySelectorAll(".filter").forEach(btn => {
    btn.classList.toggle(
      "active",
      btn.dataset.cat === cat
    );
  });

  render();

  const catalogo = document.querySelector("#catalogo");

  if (catalogo) {
    catalogo.scrollIntoView({
      behavior: "smooth"
    });
  }
}


// =========================
// PRODUCTOS
// =========================

function render() {
  const grid = document.querySelector("#grid");

  if (!grid) return;

  let list = products.filter(product => {
    return category === "Todos" || product.cat === category;
  });

  const sort = document.querySelector("#sort");

  if (sort) {
    if (sort.value === "low") {
      list.sort((a, b) => a.price - b.price);
    }

    if (sort.value === "high") {
      list.sort((a, b) => b.price - a.price);
    }
  }

  const title = document.querySelector("#catTitle");

  if (title) {
    title.textContent = category;
  }

  grid.innerHTML = list.map(product => `
    <article class="card" onclick="openProduct(${product.id})">

      <div class="card-img">
        <img
          src="${product.img}"
          alt="${product.name}"
          loading="lazy"
          onerror="this.style.display='none'"
        >
      </div>

      <div class="card-info">
        <div class="card-cat">${product.cat}</div>

        <h3>${product.name}</h3>

        <div class="card-bottom">
          <strong>${money(product.price)}</strong>
          <span>Ver producto</span>
        </div>
      </div>

    </article>
  `).join("");
}


