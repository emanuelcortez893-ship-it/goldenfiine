const mAdd = document.querySelector("#mAdd");

if (mAdd) {
  mAdd.addEventListener("click", () => {

    if (!current) return;

    const size = current.selectedSize || current.sizes[0];

    const existing = cart.find(item => {
      return item.id === current.id && item.size === size;
    });

    if (existing) {
      existing.qty++;
    } else {
      cart.push({
        id: current.id,
        name: current.name,
        price: current.price,
        img: current.img,
        size: size,
        qty: 1
      });
    }

    save();
    renderCart();

    document.querySelector("#modal")?.classList.remove("open");

    openCart();
  });
}


// =========================
// CARRITO
// =========================

function addQty(index) {
  if (!cart[index]) return;

  cart[index].qty++;

  save();
  renderCart();
}

function removeQty(index) {
  if (!cart[index]) return;

  cart[index].qty--;

  if (cart[index].qty <= 0) {
    cart.splice(index, 1);
  }

  save();
  renderCart();
}

function deleteItem(index) {
  if (!cart[index]) return;

  cart.splice(index, 1);

  save();
  renderCart();
}


function renderCart() {
  const cartItems = document.querySelector("#cartItems");
  const cartCount = document.querySelector("#cartCount");
  const cartTotal = document.querySelector("#cartTotal");

  const totalQty = cart.reduce((sum, item) => {
    return sum + item.qty;
  }, 0);

  const total = cart.reduce((sum, item) => {
    return sum + item.price * item.qty;
  }, 0);

  if (cartCount) {
    cartCount.textContent = totalQty;
  }

  if (cartTotal) {
    cartTotal.textContent = money(total);
  }

  if (!cartItems) return;

  if (cart.length === 0) {
    cartItems.innerHTML = `
      <div class="empty-cart">
        Tu carrito está vacío.
      </div>
    `;

    return;
  }

  cartItems.innerHTML = cart.map((item, index) => `
    <div class="cart-item">

      <img
        src="${item.img}"
        alt="${item.name}"
      >

      <div class="cart-item-info">

        <strong>${item.name}</strong>

        <span>${item.size}</span>

        <b>${money(item.price * item.qty)}</b>

        <div class="qty">

          <button onclick="removeQty(${index})">
            −
          </button>

          <span>${item.qty}</span>

          <button onclick="addQty(${index})">
            +
          </button>

          <button
            class="delete"
            onclick="deleteItem(${index})"
          >
            ×
          </button>

        </div>

      </div>

    </div>
  `).join("");
}


